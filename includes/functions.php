function categoryIconName(?string $stored): string {
    $stored = trim((string) $stored);
    $emoji = [
        '📁' => 'folder', '📂' => 'folder',
        '☀️' => 'sun', '🌞' => 'sun', '⚡' => 'sun',
        '💧' => 'droplet', '🌊' => 'droplet',
        '🔧' => 'wrench', '🛠️' => 'wrench',
        '📦' => 'package', '🏷️' => 'tag', '⚙️' => 'settings', '🛒' => 'cart',
    ];
    if ($stored === '') {
        return 'folder';
    }
    if (isset($emoji[$stored])) {
        return $emoji[$stored];
    }
    if (preg_match('/^[a-z][a-z0-9-]*$/', $stored)) {
        return $stored;
    }
    return 'folder';
}
