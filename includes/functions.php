// Helper Functions

function formatCurrency($amount) {
    return '฿' . number_format($amount, 2);
}

function generateOrderNo($type = 'ORD') {
    $prefix = in_array($type, ['quotation', 'QT'], true) ? 'QT' : 'ORD';
    $date = date('Ymd');
    // Continue from the highest number used today (COUNT would reuse numbers after a delete).
    $stmt = db()->prepare("SELECT MAX(CAST(SUBSTRING(order_no, ?) AS UNSIGNED)) FROM orders WHERE order_no LIKE ?");
    $stmt->execute([strlen($prefix . $date) + 1, $prefix . $date . '%']);
    $next = (int) $stmt->fetchColumn() + 1;
    return $prefix . $date . str_pad($next, 4, '0', STR_PAD_LEFT);
}

function sanitize($input) {
    return htmlspecialchars(trim($input), ENT_QUOTES, 'UTF-8');
}

function flash($key, $message = null) {
    if ($message !== null) {
        $_SESSION['flash'][$key] = $message;
    } else {
        $msg = $_SESSION['flash'][$key] ?? null;
        unset($_SESSION['flash'][$key]);
        return $msg;
    }
}

function csrfToken() {
    if (empty($_SESSION['csrf_token'])) {
        $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
    }
    return $_SESSION['csrf_token'];
}

function verifyCsrf($token) {
    return hash_equals($_SESSION['csrf_token'] ?? '', $token);
}

function redirect($url) {
    // App paths ("/admin/...") are prefixed with the install folder; full URLs pass through.
    if (strpos($url, '/') === 0 && strpos($url, '//') !== 0) {
        $url = url($url);
    }
    header("Location: $url");
    exit;
}

function getSetting($key, $default = '') {
    $stmt = db()->prepare("SELECT setting_value FROM settings WHERE setting_key = ?");
    $stmt->execute([$key]);
    $row = $stmt->fetch();
    return $row ? $row['setting_value'] : $default;
}

// VAT rate comes from ตั้งค่าระบบ (settings.tax_rate), falling back to 7%.
if (!defined('TAX_RATE')) {
    $taxSetting = getSetting('tax_rate', '7');
    define('TAX_RATE', is_numeric($taxSetting) ? (float) $taxSetting : 7.0);
    unset($taxSetting);
}

function statusLabel(string $status): string {
    return match ($status) {
        'completed' => 'เสร็จสิ้น', 'paid' => 'ชำระแล้ว', 'pending' => 'รอดำเนินการ', 'cancelled' => 'ยกเลิก', default => $status,
    };
}

function statusBadge(string $status): string {
    return match ($status) {
        'completed', 'paid' => 'success', 'pending' => 'warning', 'cancelled' => 'danger', default => 'gray',
    };
}

function orderTypeLabel(string $type): string {
    return match ($type) { 'pos' => 'POS', 'quotation' => 'ใบเสนอราคา', 'store' => 'หน้าร้าน', default => $type };
}

